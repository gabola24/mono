// ─── SKILL OVERLAY DECORATIONS ─────────────────────
// Applied to the first and last lines of a frame based on top skill categories.

const SKILL_DECORATIONS: Record<string, { top: string; side: string }> = {
  creative: { top: '~♪~', side: '✎' },
  technical: { top: '{0,1}', side: '</>' },
  philosophy: { top: '∞', side: '◎' },
  science: { top: '⚛', side: '∑' },
  design: { top: '◆', side: '▣' },
  music: { top: '♫', side: '♩' },
  writing: { top: '✒', side: '¶' },
}

function categorizeSkill(name: string): string | null {
  const n = name.toLowerCase()
  if (/music|audio|sound|rhythm|beat|melody|compos/.test(n)) return 'music'
  if (/writ|prose|poetry|narrative|story|literary/.test(n)) return 'writing'
  if (/art|creative|generat|visual|color|aesthetic|illustration/.test(n)) return 'creative'
  if (/code|program|engineer|algorithm|data|api|system/.test(n)) return 'technical'
  if (/philos|ethic|metaphys|epistem|logic|absurd|existential/.test(n)) return 'philosophy'
  if (/scien|physics|chem|bio|math|statistic|research/.test(n)) return 'science'
  if (/design|typograph|layout|ux|ui|brutalis|grid/.test(n)) return 'design'
  return null
}

function applySkillDecorations(frame: string, topSkills: string[]): string {
  if (topSkills.length === 0) return frame

  const categories = topSkills
    .map(categorizeSkill)
    .filter((c): c is string => c !== null)
  const unique = [...new Set(categories)].slice(0, 2)
  if (unique.length === 0) return frame

  const lines = frame.split('\n')
  const decos = unique.map((c) => SKILL_DECORATIONS[c]).filter(Boolean)
  if (decos.length === 0) return frame

  const topDeco = decos.map((d) => d.top).join(' ')
  const sideDeco = decos.map((d) => d.side).join('')

  const maxLen = Math.max(...lines.map((l) => l.length))
  const padded = (s: string, len: number) => s + ' '.repeat(Math.max(0, len - s.length))

  lines[0] = `${sideDeco} ${padded(lines[0].trim(), maxLen)} ${sideDeco}`
  if (lines.length > 1) {
    const mid = Math.floor(lines.length / 2)
    const center = padded('', Math.floor((maxLen - topDeco.length) / 2)) + topDeco
    lines[mid] = `  ${padded(lines[mid].trim(), maxLen)}  `
    lines[lines.length - 1] = `${center}`
  }

  return lines.join('\n')
}

